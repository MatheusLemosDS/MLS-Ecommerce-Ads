import {test} from 'node:test';
import assert from 'node:assert/strict';
import {FinanceConnectionError} from '../src/connection-store.mjs';
import {FINANCE_REFRESH_ORIGIN, buildFinanceRefreshRequest} from '../src/refresh-request.mjs';

const input={partnerKey:'fixture-signing-key-only',refreshToken:'fixture-private-rotating-token',timestamp:1792333333};
const safeError=code=>error=>{
  assert.ok(error instanceof FinanceConnectionError);
  assert.equal(error.code,code);assert.equal(error.message,code);
  assert.ok(!error.message.includes(input.refreshToken));
  assert.ok(!error.message.includes(input.partnerKey));
  return true;
};

test('refresh request uses the documented production Auth URL, public query and POST JSON types',async()=>{
  const request=await buildFinanceRefreshRequest(input),url=new URL(request.url);
  assert.equal(FINANCE_REFRESH_ORIGIN,'https://partner.shopeemobile.com');
  assert.equal(url.origin,FINANCE_REFRESH_ORIGIN);
  assert.equal(url.pathname,'/api/v2/auth/access_token/get');
  assert.deepEqual([...url.searchParams.keys()],['partner_id','timestamp','sign']);
  assert.equal(url.searchParams.get('partner_id'),'2049333');
  assert.equal(url.searchParams.get('timestamp'),'1792333333');
  // Expected digest independently generated by Python hmac/hashlib.
  assert.equal(url.searchParams.get('sign'),'1d240a3940edf3c7353a5fdccc58617afc0194651e2b38400e736a4254be15b8');
  assert.equal(request.method,'POST');assert.equal(request.headers.get('content-type'),'application/json');
  assert.deepEqual(await request.json(),{refresh_token:input.refreshToken,partner_id:2049333,shop_id:1178167501});
});
test('only the shop scope is selected, with no merchant, Ads identity or access token fields',async()=>{
  const request=await buildFinanceRefreshRequest(input),body=await request.json();
  assert.deepEqual(Object.keys(body),['refresh_token','partner_id','shop_id']);
  assert.equal(typeof body.partner_id,'number');assert.equal(typeof body.shop_id,'number');
  for(const field of ['merchant_id','access_token','code','main_account_id','partner_key'])assert.ok(!Object.hasOwn(body,field));
  assert.ok(!JSON.stringify(body).includes('2047569'));
});
test('private token stays out of query/headers and raw partner key is never transmitted',async()=>{
  const request=await buildFinanceRefreshRequest(input);
  const publicParts=request.url+JSON.stringify([...request.headers]);
  assert.ok(!publicParts.includes(input.refreshToken));
  assert.ok(!publicParts.includes(input.partnerKey));
  assert.ok(!(await request.text()).includes(input.partnerKey));
  assert.equal(request.headers.get('authorization'),null);assert.equal(request.headers.get('cookie'),null);
});
test('redirects are manual and construction never performs network requests or retries',async t=>{
  let calls=0;t.mock.method(globalThis,'fetch',()=>{calls++;throw Error('UNEXPECTED_PROVIDER_CALL');});
  const request=await buildFinanceRefreshRequest(input);
  assert.equal(request.redirect,'manual');assert.equal(calls,0);
});
test('caller cannot override host, profile, body or scope',async()=>{
  for(const extra of [{origin:'https://other.invalid'},{partner_id:2047569},{shop_id:9},{merchant_id:77},{body:{}},{access_token:'fixture'}]) {
    await assert.rejects(buildFinanceRefreshRequest({...input,...extra}),safeError('FINANCE_REFRESH_REQUEST_INVALID'));
  }
  for(const value of [null,undefined,[],{}, {partnerKey:input.partnerKey,timestamp:input.timestamp}]) {
    await assert.rejects(buildFinanceRefreshRequest(value),safeError('FINANCE_REFRESH_REQUEST_INVALID'));
  }
});
test('invalid tokens and timestamps fail with fixed errors before any request exists',async()=>{
  for(const refreshToken of [undefined,null,12,{},[], '', 'x'.repeat(8193),'private\nrefresh','private\u0000refresh']) {
    await assert.rejects(buildFinanceRefreshRequest({...input,refreshToken}),safeError('FINANCE_REFRESH_TOKEN_INVALID'));
  }
  await assert.rejects(buildFinanceRefreshRequest({...input,timestamp:1792333333000}),safeError('FINANCE_REFRESH_SIGNING_INPUT_INVALID'));
});
